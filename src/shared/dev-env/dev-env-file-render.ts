import type { DevEnvContext, DevEnvValueSource } from './dev-env-context'
import { interpolateDevEnvValue } from './dev-env-expression'
import type { DevEnvEnvFile } from './dev-env-types'

export type DevEnvFileSection = 'STATIC' | 'SECRET' | 'DYNAMIC' | 'LOCAL'

export type RenderedEnvValue = {
  key: string
  value: string
  section: DevEnvFileSection
  sources: DevEnvValueSource[]
  secret: boolean
}

const FILE_SECTIONS: readonly DevEnvFileSection[] = ['STATIC', 'SECRET', 'DYNAMIC', 'LOCAL']

type EnvEntry = { key: string; rawValue: string; index: number }

const HEADER = '# Generated by Orca Dev Environments. Edit only the LOCAL section.'
const LOCAL_MARKER = '# --- LOCAL (kept on re-render) ---'
const SECTION_MARKER = /^# --- (STATIC|SECRET|DYNAMIC|LOCAL) \(.*\) ---$/gm
// Quoted values may span lines (PEM keys) and are kept byte for byte.
const ENV_LINE =
  /^[ \t]*(?:export[ \t]+)?([A-Za-z_][A-Za-z0-9_]*)[ \t]*=[ \t]*("(?:\\.|[^"\\])*"|'[^']*'|[^\n]*)/gm

function parseEnvEntries(text: string): EnvEntry[] {
  return Array.from(text.matchAll(ENV_LINE), (match) => ({
    key: match[1],
    rawValue: match[2],
    index: match.index
  }))
}

function unquoteEnvValue(rawValue: string): string {
  const trimmed = rawValue.trim()
  if (trimmed.length >= 2 && trimmed.startsWith('"') && trimmed.endsWith('"')) {
    return trimmed
      .slice(1, -1)
      .replace(/\\(.)/g, (_match, char: string) => (char === 'n' ? '\n' : char))
  }
  if (trimmed.length >= 2 && trimmed.startsWith("'") && trimmed.endsWith("'")) {
    return trimmed.slice(1, -1)
  }
  return trimmed.replace(/\s+#.*$/, '')
}

function formatEnvValue(value: string): string {
  return /[\s#"'\\]/.test(value) ? JSON.stringify(value) : value
}

function getLocalSectionText(currentText: string | null, definedKeys: ReadonlySet<string>): string {
  if (currentText === null) {
    return ''
  }
  const markerIndex = currentText.indexOf(`${LOCAL_MARKER}\n`)
  if (markerIndex !== -1) {
    return currentText.slice(markerIndex + LOCAL_MARKER.length + 1)
  }
  if (currentText.includes(LOCAL_MARKER)) {
    return ''
  }
  // Why: a hand-written file predates Orca; keep the keys Orca does not manage.
  const adopted = parseEnvEntries(currentText).filter((entry) => !definedKeys.has(entry.key))
  return adopted.map((entry) => `${entry.key}=${entry.rawValue}\n`).join('')
}

export function renderDevEnvFile(input: {
  file: DevEnvEnvFile
  baseText: string | null
  currentText: string | null
  context: DevEnvContext
  envLabel: string
}): { text: string; values: RenderedEnvValue[] } | { error: string } {
  const managed: RenderedEnvValue[] = []
  for (const line of input.file.lines) {
    const result = interpolateDevEnvValue(line.value, input.context)
    if ('error' in result) {
      return { error: `${line.key}: ${result.error}` }
    }
    const secretOnly = result.sources.every((source) => source === 'secret')
    managed.push({
      key: line.key,
      value: result.value,
      section: secretOnly ? 'SECRET' : 'DYNAMIC',
      sources: result.sources,
      secret: result.secret
    })
  }
  const managedKeys = new Set(managed.map((value) => value.key))
  const staticEntries = parseEnvEntries(input.baseText ?? '').filter(
    (entry) => !managedKeys.has(entry.key)
  )
  const definedKeys = new Set([...managedKeys, ...staticEntries.map((entry) => entry.key)])
  const localText = getLocalSectionText(input.currentText, definedKeys)
  const secretValues = managed.filter((value) => value.section === 'SECRET')
  const dynamicValues = managed.filter((value) => value.section === 'DYNAMIC')
  const formatManaged = (values: RenderedEnvValue[]): string =>
    values.map((value) => `${value.key}=${formatEnvValue(value.value)}\n`).join('')

  const text = [
    `${HEADER}\n`,
    `# --- STATIC (${input.file.base ? `from ${input.file.base}` : 'no base file'}) ---\n`,
    staticEntries.map((entry) => `${entry.key}=${entry.rawValue}\n`).join(''),
    '# --- SECRET (Orca Dev Environments, do not edit) ---\n',
    formatManaged(secretValues),
    `# --- DYNAMIC (${input.envLabel}, do not edit) ---\n`,
    formatManaged(dynamicValues),
    `${LOCAL_MARKER}\n`,
    localText
  ].join('')

  const staticValues: RenderedEnvValue[] = staticEntries.map((entry) => ({
    key: entry.key,
    value: unquoteEnvValue(entry.rawValue),
    section: 'STATIC',
    sources: ['literal'],
    secret: false
  }))
  const localValues: RenderedEnvValue[] = parseEnvEntries(localText).map((entry) => ({
    key: entry.key,
    value: unquoteEnvValue(entry.rawValue),
    section: 'LOCAL',
    sources: ['literal'],
    secret: false
  }))
  return { text, values: [...staticValues, ...secretValues, ...dynamicValues, ...localValues] }
}

/** Values of a rendered file by section; sources cannot be recovered from text. */
export function parseRenderedDevEnvFile(text: string): RenderedEnvValue[] {
  const markers = Array.from(text.matchAll(SECTION_MARKER)).flatMap((match) => {
    const section = FILE_SECTIONS.find((name) => name === match[1])
    return section ? [{ section, index: match.index }] : []
  })
  return parseEnvEntries(text).map((entry) => {
    const section = markers.findLast((marker) => marker.index < entry.index)?.section ?? 'LOCAL'
    return {
      key: entry.key,
      value: unquoteEnvValue(entry.rawValue),
      section,
      sources: [],
      secret: section === 'SECRET'
    }
  })
}
